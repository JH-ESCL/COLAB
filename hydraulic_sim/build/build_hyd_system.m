function mdl = build_hyd_system(mdl)
%BUILD_HYD_SYSTEM  HYD_TOPOLOGY 로부터 시스템 Simulink 모델(hyd_system.slx) 자동 생성
%   build_hyd_system            -> hyd_system.slx
%   build_hyd_system('myModel')
if nargin < 1, mdl = 'hyd_system'; end
P = hyd_params();
assignin('base', 'P', P);
topo = P.topo;

if bdIsLoaded(mdl), close_system(mdl, 0); end
load_system('simulink');
new_system(mdl);
set_param(mdl, 'Solver', 'ode15s', 'MaxOrder', '2', 'StopTime', 'P.tEnd', ...
    'RelTol', '1e-3', 'AbsTol', '1e-3', 'MaxStep', '0.05', ...
    'InitFcn', 'P = hyd_params();', ...
    'AlgebraicLoopMsg', 'error', 'SignalLogging', 'off');

% ---------- 블록 배치 (열, 행) ----------
lay = struct('RSV',[0 2], 'SOV',[1 1], 'SUPL_M',[1 4], 'SUPL_E',[2 1], ...
    'EDP',[3 1], 'ACMP',[3 4], 'PFM_E',[4 0], 'PFM_M',[4 3], 'CKV_E',[5 0], 'CKV_M',[5 3], ...
    'PMAN',[6 1], 'ACC',[7 0], 'RV',[7 2], 'PLINE',[7 4], 'ACT',[8 4], 'RLINE',[9 4], ...
    'RTF',[9 2], 'CDF',[4 6], 'HX',[6 6]);
W = 130; H = 110; DX = 230; DY = 170; X0 = 300; Y0 = 60;

% ---------- 시나리오 시계 ----------
add_block('built-in/Clock', [mdl '/Clock'], 'Position', [30 20 50 40]);

nb = numel(topo.blocks);
for k = 1:nb
    bk = topo.blocks(k);
    c  = lay.(bk.name);
    pos = [X0 + c(1)*DX, Y0 + c(2)*DY, X0 + c(1)*DX + W, Y0 + c(2)*DY + H];
    hasExt = bk.extId > 0;
    hyd_add_lru(mdl, bk.name, bk.type, bk.Nin, bk.Nout, hasExt, ['P.blk.' bk.name], pos);

    % 외부 입력 (시나리오)
    if hasExt
        sc = [mdl '/SCN_' bk.name];
        add_block('simulink/User-Defined Functions/MATLAB Function', sc, ...
            'Position', [pos(1)-110, pos(4)-25, pos(1)-50, pos(4)]);
        rt = sfroot;
        ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', sc);
        ch.Script = sprintf('function e = SCN(t)\n%%#codegen\ne = hyd_scenario(t, %d);\n', bk.extId);
        add_line(mdl, 'Clock/1', ['SCN_' bk.name '/1'], 'autorouting', 'smart');
        add_line(mdl, ['SCN_' bk.name '/1'], sprintf('%s/%d', bk.name, bk.Nin + bk.Nout + 1), ...
            'autorouting', 'smart');
    end

    % 모니터 로깅
    tw = [mdl '/mon_' bk.name];
    add_block('simulink/Sinks/To Workspace', tw, 'VariableName', ['mon_' bk.name], ...
        'SaveFormat', 'Timeseries', 'Position', [pos(3)+15, pos(4)+5, pos(3)+75, pos(4)+25]);
    add_line(mdl, sprintf('%s/%d', bk.name, bk.Nin + bk.Nout + 1), ['mon_' bk.name '/1'], ...
        'autorouting', 'smart');
end

% ---------- 배관 연결: fwd(상류->하류) + bwd(하류->상류) ----------
nameIdx = containers.Map({topo.blocks.name}, num2cell(1:nb));
for c = 1:numel(topo.conns)
    cn = topo.conns(c);
    A = topo.blocks(nameIdx(cn.from));
    add_line(mdl, sprintf('%s/%d', cn.from, A.Nin + cn.out), sprintf('%s/%d', cn.to, cn.in), ...
        'autorouting', 'smart');                                   % fwd [P;T]
    add_line(mdl, sprintf('%s/%d', cn.to, cn.in), sprintf('%s/%d', cn.from, A.Nin + cn.out), ...
        'autorouting', 'smart');                                   % bwd [Q;T]
end

try
    add_block('built-in/Note', [mdl '/Hydraulic System (P-Q-T) - auto generated by build_hyd_system'], ...
        'Position', [300 10]);
catch
end
save_system(mdl);
fprintf('Model "%s" built: %d LRUs, %d connections\n', mdl, nb, numel(topo.conns));
end
